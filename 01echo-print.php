<?php
// Concept: echo and print
// These statements are used to display output in PHP.

// Simple example
echo "Hello, welcome to PHP!<br>";
print "This message is printed using print.<br>";

// A variable can also be displayed
$a = "PHP is easy to learn";
echo $a . "<br>";

// Real-world use example
// A website may use echo to show a welcome message or product name.
$productName = "Laptop";
echo "Our featured product is: " . $productName . "<br>";
?>
